// 差し込み: {{key}} を vars[key] に置換（未定義は空欄の下線に）
export function fillConsentVars(text, vars) {
  if (!text) return '';
  return String(text).replace(/\{\{([^}]+)\}\}/g, (_, k) => {
    const v = vars && vars[k.trim()];
    return (v == null || v === '') ? '　　　　' : String(v);
  });
}
